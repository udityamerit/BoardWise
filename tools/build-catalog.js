/* Writes js/data/catalog.js: for every board, its subjects (name, icon, marks, number of papers) and its paper ids.
   The site only downloads the question bank of the board a student is using (see the loader at the end of index.html), so the
   Exams pages read the other boards' subjects and counts from this small file instead. Run by tools/stamp-version.js;
   on its own:  node tools/build-catalog.js  (--check: exit 1, changing nothing, if the file is out of date). */
'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm');
const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'js/data/catalog.js');

function build() {
  const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
  const files = [...html.matchAll(/<script src="(js\/data\/[^"?]+)/g)].map(m => m[1]).filter(f => !/catalog\.js$/.test(f));
  const sb = { console: { log() {}, warn() {}, error() {} } }; sb.window = sb; sb.self = sb; vm.createContext(sb);
  files.forEach(f => vm.runInContext(fs.readFileSync(path.join(ROOT, f), 'utf8'), sb, { filename: f }));
  const bd = x => (x && x.board) || 'msbshse';
  const boards = {};
  (sb.SUBJECTS || []).forEach(s => {
    const b = boards[bd(s)] || (boards[bd(s)] = { subjects: [], papers: [] });
    b.subjects.push({ key: s.key, name: s.name, icon: s.icon, color: s.color, stream: s.stream || undefined, total: s.total, blurb: s.blurb,
      papers: (sb.PAPERS || []).filter(p => p.subject === s.key).length });
  });
  (sb.PAPERS || []).forEach(p => { (boards[bd(p)] || (boards[bd(p)] = { subjects: [], papers: [] })).papers.push(p.id); });
  return '/* Generated by tools/build-catalog.js from the question banks: do not edit by hand. */\nwindow.CATALOG = ' + JSON.stringify(boards) + ';\n';
}

function run(check) {
  const src = build(), cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (cur === src) return false;
  if (!check) fs.writeFileSync(OUT, src);
  return true;
}
module.exports = { build, run };
if (require.main === module) {
  const check = process.argv.includes('--check'), stale = run(check);
  console.log(stale ? (check ? 'OUT OF DATE: run node tools/build-catalog.js' : 'js/data/catalog.js written') : 'js/data/catalog.js up to date');
  if (check && stale) process.exit(1);
}
